import { expect, test } from '@playwright/test';
test.beforeEach(async ({ request }) => { await request.post('http://127.0.0.1:8787/api/test/reset'); });
test('account → capture → import → review → export works on the project path', async ({ page, request }) => {
  await page.goto('./#/cuentas');
  await page.getByLabel('Nombre de la cuenta', { exact: true }).fill('Ahorros de prueba');
  await page.getByLabel('Saldo inicial (COP)').fill('1.000.000');
  await page.getByLabel('Fecha del saldo inicial').fill('2026-01-01');
  await page.getByRole('heading', { name: 'Agregar cuenta', exact: true }).locator('..').getByRole('button', { name: 'Guardar', exact: true }).click();
  await expect(page.locator('.account-row')).toContainText('Ahorros de prueba');
  const state = await (await request.get('http://127.0.0.1:8787/api/state')).json();
  const device = await (await request.post('http://127.0.0.1:8787/api/devices', { data: { name: 'Synthetic phone' } })).json();
  const capture = await request.post('http://127.0.0.1:8787/api/capture-events', { headers: { Authorization: `Bearer ${device.token}` }, data: { eventId: 'purchase', source: 'wallet', observedAt: '2026-10-05T18:00:00Z', date: '2026-10-05', accountId: state.accounts[0].id, amountMinor: '1250000', merchant: 'Café de ejemplo', location: { latitude: 4.60971, longitude: -74.08175, accuracy: 24, observedAt: '2026-10-05T18:00:02Z' } } });
  expect(capture.status()).toBe(202);
  await expect.poll(async () => (await (await request.get('http://127.0.0.1:8787/api/state')).json()).transactions.length).toBe(1);
  await page.getByRole('link', { name: 'Importar', exact: true }).click();
  await page.getByLabel('Cuenta del archivo').selectOption(state.accounts[0].id);
  await page.getByLabel('Archivo CSV o Excel').setInputFiles({ name: 'sample.csv', mimeType: 'text/csv', buffer: Buffer.from('Fecha;Descripcion;Valor;Moneda;Tipo\n2026-10-05;Café de ejemplo;12.500,00;COP;gasto') });
  await page.getByRole('button', { name: 'Subir y previsualizar' }).click();
  await page.getByRole('button', { name: 'Confirmar 1 filas aceptadas' }).click();
  await expect(page.getByText('Completado', { exact: true }).first()).toBeVisible();
  await page.getByRole('link', { name: /Revisar/ }).click();
  await page.getByRole('button', { name: /Unir con Café de ejemplo/ }).click();
  await expect(page.getByRole('heading', { name: 'Todo en su lugar' })).toBeVisible();
  await page.getByRole('link', { name: 'Resumen', exact: true }).click();
  await expect(page.locator('.available-total > strong')).toHaveText('$ 987.500');
  await page.reload(); await expect(page.locator('.available-total > strong')).toHaveText('$ 987.500');
  await page.getByRole('link', { name: 'Movimientos', exact: true }).click();
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('button', { name: 'Café de ejemplo', exact: true }).click();
  await expect(page.getByText('Ubicación guardada por el atajo')).toBeVisible();
  await expect(page.getByRole('link', { name: 'Abrir en Mapas' })).toHaveAttribute('href', 'https://maps.apple.com/?ll=4.60971,-74.08175');
  await page.getByRole('button', { name: 'Cerrar' }).click();
  const downloaded = page.waitForEvent('download'); await page.getByRole('button', { name: 'CSV', exact: true }).click();
  expect((await downloaded).suggestedFilename()).toBe('money-stalker.csv');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
